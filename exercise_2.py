# 16. How does unsupervised learning differ from supervised learning?
# ------------------------------------------------------------------------------

"""
Answer:
In supervised learning, algorithms are provided with ground-truth target labels (correct outputs) 
to guide model training[cite: 53]. In unsupervised learning, the data is completely unlabeled, 
and the algorithm must extract structures, groupings, and patterns on its own without guidance[cite: 53, 54].
"""


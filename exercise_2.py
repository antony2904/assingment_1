# 13. Compare Supervised and Unsupervised Learning.
# ------------------------------------------------------------------------------

"""
Answer:
- Supervised Learning: Uses labeled datasets where inputs and correct target outputs are known, 
  aiming to learn a mapping to predict outcomes on new data (e.g., classification, regression)[cite: 53].
- Unsupervised Learning: Uses unlabeled data ("learning without a teacher") to discover 
  hidden patterns, structures, clusters, or associations without predefined outputs[cite: 53, 54, 55].
"""

# 14. Explain the difference between classification and regression.
# ------------------------------------------------------------------------------

"""
Answer:
- Classification: A supervised learning task where the model learns to categorize data 
  into predefined discrete classes (e.g., classifying emails as "spam" or "not spam")[cite: 53].
- Regression: A supervised learning task that involves predicting a continuous numeric 
  value (e.g., predicting the price of a car based on features like mileage and age)[cite: 53].
"""

